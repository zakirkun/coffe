package backup

import (
	"context"
	"errors"
	"fmt"
	"io"
	"os"

	"filippo.io/age"
)

type ExportOptions struct {
	DatabasePath string
	OutputPath   string
	Passphrase   string
}

func Export(ctx context.Context, options ExportOptions) (err error) {
	if err := validatePassphrase(options.Passphrase); err != nil {
		return err
	}
	databasePath, err := cleanPath(options.DatabasePath)
	if err != nil {
		return err
	}
	outputPath, err := cleanPath(options.OutputPath)
	if err != nil {
		return err
	}
	if databasePath == outputPath {
		return fmt.Errorf("backup output equals database path: %w", ErrInvalidBackup)
	}
	snapshotPath, err := snapshot(ctx, databasePath)
	if err != nil {
		return err
	}
	defer func() { err = errors.Join(err, removeIfExists(snapshotPath)) }()
	source, err := os.Open(snapshotPath) //nolint:gosec // snapshotPath is generated by os.CreateTemp.
	if err != nil {
		return fmt.Errorf("open snapshot: %w", err)
	}
	defer func() { err = errors.Join(err, source.Close()) }()
	recipient, err := age.NewScryptRecipient(options.Passphrase)
	if err != nil {
		return fmt.Errorf("create backup recipient: %w", err)
	}
	destination, err := os.OpenFile(outputPath, os.O_CREATE|os.O_EXCL|os.O_WRONLY, 0o600) //nolint:gosec // output is absolute, exclusive, and mode 0600.
	if err != nil {
		return fmt.Errorf("create encrypted backup: %w", err)
	}
	succeeded := false
	defer func() {
		err = errors.Join(err, destination.Close())
		if !succeeded {
			err = errors.Join(err, removeIfExists(outputPath))
		}
	}()
	encrypted, err := age.Encrypt(destination, recipient)
	if err != nil {
		return fmt.Errorf("start backup encryption: %w", err)
	}
	if _, err := io.Copy(encrypted, io.LimitReader(source, maxBackupBytes+1)); err != nil {
		return fmt.Errorf("encrypt backup: %w", err)
	}
	if position, err := source.Seek(0, io.SeekCurrent); err != nil {
		return fmt.Errorf("measure snapshot: %w", err)
	} else if position > maxBackupBytes {
		return fmt.Errorf("snapshot exceeds size limit: %w", ErrInvalidBackup)
	}
	if err := encrypted.Close(); err != nil {
		return fmt.Errorf("finish backup encryption: %w", err)
	}
	succeeded = true
	return nil
}
